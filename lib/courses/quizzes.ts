export function getQuiz(n: number): Quiz | undefined {
  return QUIZ_SET.find((q) => q.n === n);
}

/** Версія без ключів відповідей — для клієнтського компонента. */
export function publicQuiz(q: Quiz): PublicQuiz {
  return { n: q.n, title: q.title, questions: q.questions.map(({ q: text, options }) => ({ q: text, options })) };
}

/** Оцінка: 1 бал за правильну відповідь; питання-рефлексія (correct=null) — бал за будь-яку. */
export function grade(q: Quiz, answers: unknown): { score: number; wrong: number[] } {
  const wrong: number[] = [];
  let score = 0;
  q.questions.forEach((it, i) => {
    const a = Array.isArray(answers) ? answers[i] : undefined;
    const valid = Number.isInteger(a) && (a as number) >= 0 && (a as number) < it.options.length;
    if (valid && (it.correct === null || it.correct === a)) score++;
    else wrong.push(i);
  });
  return { score, wrong };
}
